using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace TeleCloud.Querying.Generators;

[Generator]
public sealed class SortExtensionsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: (node, _) => node is ClassDeclarationSyntax or RecordDeclarationSyntax or StructDeclarationSyntax,
                transform: (ctx, _) =>
                {
                    if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) is not INamedTypeSymbol typeSymbol)
                        return null;
                    var hasAttr = typeSymbol.GetAttributes().Any(a =>
                        a.AttributeClass?.ToDisplayString() == "TeleCloud.Querying.DynamicSortAttribute");
                    return hasAttr ? typeSymbol : null;
                });

        var collected = provider.Collect();

        context.RegisterSourceOutput(collected, (spc, symbols) =>
        {
            foreach (var symbol in symbols)
            {
                if (symbol is null) continue;

                var source = GenerateExtensionClass(symbol);
                spc.AddSource($"{symbol.Name}SortExtensions.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    private static string GenerateExtensionClass(INamedTypeSymbol typeSymbol)
    {
        var typeName = typeSymbol.Name;
        var fullTypeName = typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var ns = typeSymbol.ContainingNamespace.ToDisplayString();

        var properties = typeSymbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => p.DeclaredAccessibility == Accessibility.Public
                        && !p.IsStatic
                        && p.GetMethod is not null)
            .ToList();

        var propNames = string.Join(", ", properties.Select(p => p.Name));
        var hashSetInit = string.Join(", ", properties.Select(p => $"\"{p.Name}\""));

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Diagnostics.CodeAnalysis;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"public static class {typeName}SortExtensions");
        sb.AppendLine("{");

        AppendSortableProperties(sb, typeName, hashSetInit, propNames);
        sb.AppendLine();
        AppendSingleSortMethod(sb, typeName, fullTypeName, properties, propNames, isThenBy: false);
        sb.AppendLine();
        AppendSingleSortMethod(sb, typeName, fullTypeName, properties, propNames, isThenBy: true);
        sb.AppendLine();
        AppendMultiSortMethod(sb, typeName, fullTypeName);

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void AppendSortableProperties(StringBuilder sb, string typeName, string hashSetInit, string propNames)
    {
        sb.AppendLine($"    private static readonly HashSet<string> SortableProperties = new(StringComparer.OrdinalIgnoreCase)");
        sb.AppendLine("    {");
        sb.AppendLine($"        {hashSetInit}");
        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine($"    public static bool TryValidateSorts(IEnumerable<global::TeleCloud.Querying.SortDescriptor> sorts, [NotNullWhen(false)] out string? error)");
        sb.AppendLine("    {");
        sb.AppendLine("        foreach (var sort in sorts)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (!SortableProperties.Contains(sort.PropertyName))");
        sb.AppendLine("            {");
        sb.AppendLine($"                error = $\"Property '{{sort.PropertyName}}' not found on {typeName}. Available: {propNames}.\";");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("        error = null;");
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
    }

    private static void AppendSingleSortMethod(
        StringBuilder sb,
        string typeName,
        string fullTypeName,
        List<IPropertySymbol> properties,
        string propNames,
        bool isThenBy)
    {
        var methodName = isThenBy ? "ThenBy" : "OrderBy";
        var sourceType = isThenBy ? "IOrderedQueryable" : "IQueryable";
        var descMethod = isThenBy ? "ThenByDescending" : "OrderByDescending";
        var ascMethod = isThenBy ? "ThenBy" : "OrderBy";

        sb.AppendLine($"    public static IOrderedQueryable<{fullTypeName}> {methodName}(this {sourceType}<{fullTypeName}> source, global::TeleCloud.Querying.SortDescriptor sort)");
        sb.AppendLine("    {");
        sb.AppendLine("        var descending = sort.Descending;");
        sb.AppendLine("        return sort.PropertyName.ToLowerInvariant() switch");
        sb.AppendLine("        {");

        foreach (var prop in properties)
        {
            var key = prop.Name.ToLowerInvariant();
            sb.AppendLine($"            \"{key}\" => descending ? source.{descMethod}(x => x.{prop.Name}) : source.{ascMethod}(x => x.{prop.Name}),");
        }

        sb.AppendLine($"            _ => throw new ArgumentException($\"Property '{{sort.PropertyName}}' not found on {typeName}. Available: {propNames}.\")");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
    }

    private static void AppendMultiSortMethod(
        StringBuilder sb,
        string typeName,
        string fullTypeName)
    {
        sb.AppendLine($"    public static IOrderedQueryable<{fullTypeName}> OrderBy(this IQueryable<{fullTypeName}> source, IEnumerable<global::TeleCloud.Querying.SortDescriptor> sorts)");
        sb.AppendLine("    {");
        sb.AppendLine("        using var enumerator = sorts.GetEnumerator();");
        sb.AppendLine("        if (!enumerator.MoveNext())");
        sb.AppendLine("            throw new ArgumentException(\"At least one sort is required.\", nameof(sorts));");
        sb.AppendLine();
        sb.AppendLine("        var ordered = source.OrderBy(enumerator.Current);");
        sb.AppendLine("        while (enumerator.MoveNext())");
        sb.AppendLine("            ordered = ordered.ThenBy(enumerator.Current);");
        sb.AppendLine("        return ordered;");
        sb.AppendLine("    }");
    }
}
